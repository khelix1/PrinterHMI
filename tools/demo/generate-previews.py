#!/usr/bin/env python3
"""Rebuild deterministic geometric demo previews; Pillow is needed only for regeneration."""
from pathlib import Path
from PIL import Image,ImageDraw
import io
root=Path(__file__).resolve().parents[2]
output=['/* Generated by tools/demo/generate-previews.py; do not edit by hand. */']
for index in range(3):
 image=Image.new('RGBA',(900,520),(0,0,0,0));d=ImageDraw.Draw(image)
 # A fixed isometric projection keeps all exported resolutions identical.
 def p(x,y,z):return (450+int((x-y)*3),380+int((x+y)*1.2-z*3))
 def box(x,y,z,w,h,t,palette):
  d.polygon([p(x,y,z),p(x+w,y,z),p(x+w,y,z+t),p(x,y,z+t)],fill=palette[0])
  d.polygon([p(x+w,y,z),p(x+w,y+h,z),p(x+w,y+h,z+t),p(x+w,y,z+t)],fill=palette[1])
  d.polygon([p(x,y,z+t),p(x+w,y,z+t),p(x+w,y+h,z+t),p(x,y+h,z+t)],fill=palette[2])
 palettes=[('#a77622','#cb9635','#f5c457'),('#235c8e','#3482b7','#64b4ea'),('#6953a5','#8a6bcc','#b398f2')]
 palette=palettes[index]
 if index==0:
  box(-65,-38,0,130,76,8,palette);box(-54,-26,8,16,52,70,palette);box(38,-26,8,16,52,70,palette);box(-38,-8,58,76,16,12,palette)
 elif index==1:
  box(-65,-34,0,130,68,8,palette);box(-65,22,8,130,12,57,palette);box(-65,-34,8,12,56,20,palette);box(53,-34,8,12,56,20,palette)
 else:
  box(-38,-38,0,76,76,76,palette)
  for z in range(8,76,8):d.line([p(-38,-38,z),p(38,-38,z),p(38,38,z)],fill=(78,59,124,160),width=1)
 stream=io.BytesIO();image.save(stream,format='PNG',optimize=True);png=stream.getvalue()
 small=Image.new('RGB',image.size,'#101b27');small.paste(image,mask=image.getchannel('A'));small=small.resize((286,165),Image.Resampling.LANCZOS)
 rgb=small.tobytes();pixels=[((rgb[i]>>3)<<11)|((rgb[i+1]>>2)<<5)|(rgb[i+2]>>3) for i in range(0,len(rgb),3)]
 output.append(f'static const uint8_t preview_{index}_png[]={{\n'+''.join(','.join(f'0x{x:02x}' for x in png[i:i+24])+',\n' for i in range(0,len(png),24))+'};')
 output.append(f'static const uint16_t preview_{index}_rgb[]={{\n'+''.join(','.join(f'0x{x:04x}' for x in pixels[i:i+20])+',\n' for i in range(0,len(pixels),20))+'};')
import sys
content='\n'.join(output)+'\n'
if '--check' in sys.argv:
 assert (root/'main/demo_preview_assets.inc').read_text()==content,'Demo previews need regeneration'
else:(root/'main/demo_preview_assets.inc').write_text(content)
print(('PASS: verified' if '--check' in sys.argv else 'Wrote')+' main/demo_preview_assets.inc: three PNG originals and bounded RGB565 previews')
