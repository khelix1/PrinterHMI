#!/usr/bin/env python3
"""Derive browser defaults from the firmware's actual palette and layout tables."""
from pathlib import Path
import json,re,sys
root=Path(__file__).resolve().parents[2]
s=(root/'main/custom_theme.c').read_text();header=(root/'main/ui_theme.h').read_text()
routes=re.findall(r'\{"([a-z_0-9]+)", (0x\w+), (0x\w+), (0x\w+), COLOR_\w+\}',s)
assert len(routes)==58
studio={}
for match in re.finditer(r'ui_theme_studio_color\((0x\w+), (0x\w+), (0x\w+), (0x\w+)\)',header):
 a,b,c,d=match.groups();studio[(a,b,c)]='#'+d[2:].upper()
assert len(studio)==58

def block(source, name):
 m=re.search(r'(?:\b'+re.escape(name)+r'\s*=|\.'+re.escape(name)+r'\s*=)\s*\{',source);assert m,name
 start=m.end();depth=1
 for i in range(start,len(source)):
  if source[i]=='{':depth+=1
  elif source[i]=='}':
   depth-=1
   if not depth:return source[start:i]
 raise ValueError(name)
regions={'dashboard':['banner','active_print','machine_status','command_bar'],'drybox':['environment','drying_system','material_program'],'printer':['active','status','actions'],'files':['breadcrumb','up','search','sort','refresh','list'],'network':['wifi','moonraker','networks','actions'],'settings':['banner','content'],'telemetry':['metric_1','metric_2','metric_3','metric_4','charts']}
profiles={}
for base in ['operator','foundry','glass']:
 dashboards=block((root/'main/ui_dashboard_layout_profile.c').read_text(),'s_'+base)
 pages=block((root/'main/ui_page_layout_profile.c').read_text(),'s_'+base)
 layouts={}
 for page,names in regions.items():
  src=dashboards if page=='dashboard' else block(pages,page);items={}
  for name in names:
   if name.startswith('metric_'):
    xs=re.search(r'\.metric_x\s*=\s*\{([^}]+)\}',src).group(1).split(',');coords=[int(xs[int(name[-1])-1]),112,186,72]
   else:coords=[int(n.strip()) for n in block(src,name).split(',') if n.strip()]
   assert len(coords)==4,(page,name,coords)
   items[name]=dict(zip(['x','y','width','height'],coords));items[name]['visible']=True
  layouts[page]=items
 profiles[base]=layouts
palette={base:{name:('#'+[a,b,c][i][2:]).upper() for name,a,b,c in routes} for i,base in enumerate(['operator','foundry','glass'])}
palette['studio']={name:studio[(a,b,c)] for name,a,b,c in routes}
legacy=[r[0] for r in routes[:25]]+['accent','accent_bright']
spec={'format':'printerhmi.theme','maxBytes':49152,'maxDepth':16,'legacyKeys':legacy,'keys':[r[0] for r in routes],'palettes':palette,'layouts':profiles,'regions':regions,'metrics':{'studio':{'radius_card':18,'radius_button':24,'radius_panel':18,'surface_opacity':255},'operator':{'radius_card':12,'radius_button':10,'radius_panel':10,'surface_opacity':255},'foundry':{'radius_card':20,'radius_button':18,'radius_panel':20,'surface_opacity':255},'glass':{'radius_card':22,'radius_button':20,'radius_panel':24,'surface_opacity':255}}}
output='/* Generated by generate-spec.py from firmware tables. */\n(function(g){const spec='+json.dumps(spec,separators=(',',':'))+';if(typeof module!=="undefined"&&module.exports)module.exports=spec;else g.ThemeSpec=spec;})(globalThis);\n'
p=Path(__file__).with_name('theme-spec.js')
if '--check' in sys.argv:
 if not p.exists() or p.read_text()!=output:raise SystemExit('Theme spec is stale; run generate-spec.py')
 print('PASS: browser schema defaults match firmware palette/layout tables')
else:p.write_text(output)
